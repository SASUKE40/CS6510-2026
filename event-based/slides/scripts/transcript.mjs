// Builds TRANSCRIPT.md from the speaker notes in the deck and checks them
// against the ASD-STE-100 limits used for this talk.
// Each note starts with a timing tag: [m:ss] for the talk, [backup] for Q&A.
import { writeFile } from 'node:fs/promises'
import { load } from '@slidev/parser/fs'

const WORDS_PER_MINUTE = 130
const MAX_SENTENCE_WORDS = 20
// STE allows -ing words only in technical names; these are names or nouns here.
const ING_ALLOWED = new Set(['string', 'thing', 'nothing', 'something', 'during', 'pending', 'decoupling', 'evening'])

const root = new URL('..', import.meta.url).pathname
const deck = await load(root, `${root}slides.md`)

const parseTime = (tag) => {
  const [m, s] = tag.split(':').map(Number)
  return m * 60 + s
}
const format = (seconds) => `${Math.floor(seconds / 60)}:${String(Math.round(seconds % 60)).padStart(2, '0')}`

const talk = []
const backup = []
const warnings = []

for (const slide of deck.slides) {
  const note = (slide.note ?? '').trim()
  if (!note) continue
  const [first, ...rest] = note.split('\n')
  const tag = first.match(/^\[(\d+:\d{2}|backup)\]$/)?.[1]
  const page = slide.index + 1
  const title = (slide.title ?? `Slide ${page}`)
    .replace(/<[^>]+>/g, '')
    .replace(/\s*\{[^}]*\}\s*$/, '')
    .trim()
  if (!tag) {
    warnings.push(`slide ${page} (${title}): note has no [m:ss] or [backup] tag`)
    continue
  }
  const sentences = rest
    .join(' ')
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter(Boolean)
  for (const sentence of sentences) {
    const words = sentence.split(/\s+/).length
    if (words > MAX_SENTENCE_WORDS) {
      warnings.push(`slide ${page}: ${words} words: "${sentence}"`)
    }
    // Case-sensitive, so all-caps state names such as COMPENSATING pass.
    for (const word of sentence.match(/\b[A-Za-z]+ing\b/g) ?? []) {
      if (!ING_ALLOWED.has(word.toLowerCase())) warnings.push(`slide ${page}: -ing word "${word}" in "${sentence}"`)
    }
  }
  const entry = {
    page,
    title,
    seconds: tag === 'backup' ? 0 : parseTime(tag),
    words: sentences.join(' ').split(/\s+/).length,
    sentences,
  }
  ;(tag === 'backup' ? backup : talk).push(entry)
}

const planned = talk.reduce((sum, e) => sum + e.seconds, 0)
const words = talk.reduce((sum, e) => sum + e.words, 0)
const spoken = (words / WORDS_PER_MINUTE) * 60

const section = (entry, withTime) =>
  [
    `### Slide ${entry.page} · ${entry.title}${withTime ? ` · ${format(entry.seconds)}` : ''}`,
    '',
    entry.sentences.join(' '),
    '',
  ].join('\n')

const markdown = [
  '# Transcript: event-based code walkthrough',
  '',
  '<!-- Generated by `pnpm transcript` from the speaker notes in slides.md and pages/*.md. Edit the notes, not this file. -->',
  '',
  `- Planned time: **${format(planned)}** (sum of the slide timing tags).`,
  `- Spoken words: ${words}. At ${WORDS_PER_MINUTE} words per minute, the speech takes about ${format(spoken)}. The rest of the planned time is for clicks and demos.`,
  `- Style: ASD-STE-100. Sentences have ${MAX_SENTENCE_WORDS} words or fewer, active voice, and simple tenses.`,
  '- Presenter mode (`/presenter/` in `pnpm dev`) shows the same text beside each slide.',
  '',
  '## Talk',
  '',
  ...talk.map((e) => section(e, true)),
  '## Backup answers for Q&A',
  '',
  ...backup.map((e) => section(e, false)),
].join('\n')

await writeFile(`${root}TRANSCRIPT.md`, markdown)

console.log(`slides with notes: ${talk.length} talk + ${backup.length} backup`)
console.log(`planned ${format(planned)} · ${words} words ≈ ${format(spoken)} spoken`)
for (const warning of warnings) console.warn(`warning: ${warning}`)
if (planned < 15 * 60 || planned > 20 * 60) console.warn(`warning: planned time ${format(planned)} is outside 15-20 min`)
console.log('wrote TRANSCRIPT.md')
